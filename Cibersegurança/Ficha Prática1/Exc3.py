#Dimensões do retângulo
largura = float(input("Introduza a largura do retângulo (m.): "))
altura = float(input("Introduza a altura do retângulo (m.): "))

#Calcular a área e o perímetro
area = largura * altura
perimetro = 2 * (largura + altura)

#Apresentar os resultados
print(f"area: {area} m2 ")
print(f"perimetro: {perimetro} m. ")
