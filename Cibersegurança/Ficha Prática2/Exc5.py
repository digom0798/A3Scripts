#Valores
Numero1 = int(input("Escreve um valor: "))
Numero2 = int(input("Escreve um valor: "))

#Calculo do maior e do menor
if Numero1 < Numero2:
    print (f"Menor: {Numero1}")
else:
    print (f"Menor: {Numero2}")


if Numero1 > Numero2:
    print (f"Maior: {Numero1}")
else:
    print (f"Maior: {Numero2}")
