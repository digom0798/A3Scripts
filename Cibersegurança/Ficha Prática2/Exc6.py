#Valores
Numero1 = int(input("Escreve um número aqui: "))
Numero2 = int(input("Escreve um número aqui: "))

#Calcular o maior e o menor
if Numero1 < Numero2:
    print(f"Maior: {Numero2}")
else:
    print(f"Maior: {Numero1}")

if Numero1 > Numero2:
    print(f"Menor: {Numero2}")
else:
    print(f"Menor: {Numero1}")